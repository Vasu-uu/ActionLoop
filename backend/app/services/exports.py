import html
import io
import json
import re
import zipfile
from datetime import date, timedelta

from ..schemas import MeetingOut, TaskOut
from .transcript import format_ts

CSV_FIELDS = [
    "id", "title", "description", "owner", "owner_confidence", "deadline_raw", "deadline", "priority", "status",
    "needs_clarification", "verified", "evidence_quote",
]


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:50] or "meeting"


def filename(m: MeetingOut, ext: str) -> str:
    return f"{_slug(m.title)}-{m.date.isoformat()}.{ext}"


def _due(t: TaskOut) -> str:
    return t.deadline_resolved.isoformat() if t.deadline_resolved else (f"{t.deadline_raw} (unresolved)" if t.deadline_raw else "-")


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


# ---------- Markdown ----------
def to_markdown(m: MeetingOut) -> str:
    L = [f"# {m.title}", "", f"**Date:** {m.date.isoformat()}  ", f"**Attendees:** {', '.join(m.attendees) or 'not provided'}  ",
         f"**Generated by:** ActionLoop ({m.provider})", ""]
    if m.summary:
        L += ["## Summary", ""] + [f"- {b}" for b in m.summary.bullets] + ["", m.summary.paragraph, ""]
    if m.decisions:
        L += ["## Decisions", ""]
        for d in m.decisions:
            flag = "" if d.verified else " ⚠️ _unverified quote_"
            L.append(f"- **{d.decision}**{flag}" + (f" — {d.rationale}" if d.rationale else ""))
            L.append(f'  > "{d.evidence_quote}"')
        L.append("")
    L += ["## Action items", ""]
    if m.tasks:
        L += ["| Done | Task | Owner | Due | Priority | Notes |", "|---|---|---|---|---|---|"]
        for t in m.tasks:
            notes = "; ".join(t.clarification_reasons)
            L.append(f"| {'[x]' if t.status == 'done' else '[ ]'} | {_cell(t.title)} | {_cell(t.owner or 'TBD')} | {_due(t)} | {t.priority} | {_cell(notes)} |")
    else:
        L.append("_No action items._")
    L.append("")
    flagged = [t for t in m.tasks if t.needs_clarification]
    if flagged:
        L += ["## Needs clarification", ""] + [f"- **{t.title}**: {'; '.join(t.clarification_reasons)}" for t in flagged] + [""]
    if m.open_questions:
        L += ["## Open questions", ""] + [f"- {q.question}" + (f" _(suggested: {q.suggested_owner})_" if q.suggested_owner else "") for q in m.open_questions] + [""]
    if m.risks:
        L += ["## Risks", ""] + [f"- [{r.severity.upper()}] {r.risk}" for r in m.risks] + [""]
    if m.topics:
        L += ["**Topics:** " + ", ".join(m.topics), ""]
    return "\n".join(L)


# ---------- CSV ----------
def to_csv(m: MeetingOut) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=CSV_FIELDS, lineterminator="\r\n")
    w.writeheader()
    for t in m.tasks:
        row = {
            "id": t.id, "title": t.title, "description": t.description, "owner": t.owner or "",
            "owner_confidence": t.owner_confidence, "deadline_raw": t.deadline_raw or "",
            "deadline": t.deadline_resolved.isoformat() if t.deadline_resolved else "", "priority": t.priority,
            "status": t.status, "needs_clarification": "yes" if t.needs_clarification else "no",
            "verified": "yes" if t.verified else "no", "evidence_quote": t.evidence_quote,
        }
        # neutralise spreadsheet formula injection
        for k, v in row.items():
            if isinstance(v, str) and v[:1] in ("=", "+", "-", "@", "\t", "\r"):
                row[k] = "'" + v
        w.writerow(row)
    return buf.getvalue()


# ---------- ICS ----------
def _ics_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\r", "").replace("\n", "\\n")


def _fold(line: str) -> str:
    raw = line.encode("utf-8")
    if len(raw) <= 75:
        return line
    parts, cur = [], b""
    for ch in line:
        b = ch.encode("utf-8")
        if len(cur) + len(b) > (75 if not parts else 74):
            parts.append(cur.decode("utf-8"))
            cur = b
        else:
            cur += b
    parts.append(cur.decode("utf-8"))
    return "\r\n ".join(parts)


def to_ics(m: MeetingOut) -> str:
    stamp = "20260101T000000Z"
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//ActionLoop//Meeting-to-Action//EN", "CALSCALE:GREGORIAN", "METHOD:PUBLISH",
             f"X-WR-CALNAME:{_ics_escape(m.title)} action items"]
    for t in m.tasks:
        if not t.deadline_resolved:
            continue
        d: date = t.deadline_resolved
        uid = hashlib.sha1(f"{m.id}:{t.id}".encode()).hexdigest()[:20] + "@actionloop"
        desc = f"Owner: {t.owner or 'TBD'}\nPriority: {t.priority}\nFrom meeting: {m.title}"
        if t.description:
            desc += f"\n{t.description}"
        lines += [
            "BEGIN:VEVENT", f"UID:{uid}", f"DTSTAMP:{stamp}",
            f"DTSTART;VALUE=DATE:{d.strftime('%Y%m%d')}", f"DTEND;VALUE=DATE:{(d + timedelta(days=1)).strftime('%Y%m%d')}",
            f"SUMMARY:{_ics_escape('[' + (t.owner or 'TBD') + '] ' + t.title)}", f"DESCRIPTION:{_ics_escape(desc)}",
            "TRANSP:TRANSPARENT", "END:VEVENT",
        ]
    lines.append("END:VCALENDAR")
    return "\r\n".join(_fold(x) for x in lines) + "\r\n"


# ---------- Slack / Teams ----------
def to_slack(m: MeetingOut) -> str:
    L = [f"*📝 {m.title}* — {m.date.isoformat()}", ""]
    if m.summary:
        L += ["*TL;DR*"] + [f"• {b}" for b in m.summary.bullets] + [""]
    if m.decisions:
        L += ["*✅ Decisions*"] + [f"• {d.decision}" for d in m.decisions] + [""]
    if m.tasks:
        L.append("*📋 Action items*")
        for t in m.tasks:
            warn = " ⚠️" if t.needs_clarification else ""
            L.append(f"• [{t.status.replace('_', ' ')}] {t.title} — _{t.owner or 'unassigned'}_ — due {_due(t)}{warn}")
        L.append("")
    if m.open_questions:
        L += ["*❓ Open questions*"] + [f"• {q.question}" for q in m.open_questions] + [""]
    if m.risks:
        L += ["*⚠️ Risks*"] + [f"• ({r.severity}) {r.risk}" for r in m.risks]
    return "\n".join(L).strip() + "\n"


# ---------- JSON ----------
def to_json(m: MeetingOut) -> str:
    return json.dumps(json.loads(m.model_dump_json()), indent=2, ensure_ascii=False)


# ---------- HTML (shareable, read-only) ----------
def to_html(m: MeetingOut) -> str:
    e = html.escape
    pr = {"high": "#dc2626", "medium": "#d97706", "low": "#16a34a"}
    rows = "".join(
        f"<tr><td>{e(t.title)}{'' if t.verified else ' <span class=warn>unverified</span>'}</td><td>{e(t.owner or 'TBD')}</td>"
        f"<td>{e(_due(t))}</td><td style='color:{pr.get(t.priority, '#555')}'>{e(t.priority)}</td><td>{e(t.status.replace('_', ' '))}</td></tr>"
        for t in m.tasks
    ) or "<tr><td colspan=5>No action items</td></tr>"
    seg = "".join(
        f"<p><span class=ts>{e(format_ts(s.start))}</span> <b>{e(s.speaker or '')}</b> {e(s.text)}</p>" for s in m.segments
    )
    bullets = "".join(f"<li>{e(b)}</li>" for b in (m.summary.bullets if m.summary else []))
    dec = "".join(f"<li><b>{e(d.decision)}</b><br><q>{e(d.evidence_quote)}</q></li>" for d in m.decisions)
    qs = "".join(f"<li>{e(q.question)}</li>" for q in m.open_questions)
    rk = "".join(f"<li>[{e(r.severity)}] {e(r.risk)}</li>" for r in m.risks)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{e(m.title)} — ActionLoop report</title>
<style>:root{{color-scheme:light dark}}body{{font:16px/1.55 system-ui,sans-serif;max-width:860px;margin:2rem auto;padding:0 1rem}}
table{{border-collapse:collapse;width:100%}}td,th{{border:1px solid #8884;padding:.45rem .6rem;text-align:left;vertical-align:top}}
.warn{{background:#f59e0b33;color:#b45309;border-radius:4px;padding:0 .35rem;font-size:.8em}}.ts{{color:#888;font-size:.8em}}
h1{{margin-bottom:.2rem}}.meta{{color:#888}}q{{color:#888}}details{{margin-top:2rem}}</style></head><body>
<h1>{e(m.title)}</h1><div class="meta">{e(m.date.isoformat())} · {e(', '.join(m.attendees) or 'attendees not provided')} · generated by ActionLoop</div>
<h2>Summary</h2><ul>{bullets}</ul><p>{e(m.summary.paragraph if m.summary else '')}</p>
<h2>Decisions</h2><ul>{dec or '<li>None</li>'}</ul>
<h2>Action items</h2><table><tr><th>Task</th><th>Owner</th><th>Due</th><th>Priority</th><th>Status</th></tr>{rows}</table>
<h2>Open questions</h2><ul>{qs or '<li>None</li>'}</ul><h2>Risks</h2><ul>{rk or '<li>None</li>'}</ul>
<details><summary>Transcript</summary>{seg}</details></body></html>"""


# ---------- ZIP ----------
def to_zip(m: MeetingOut, emails_md: str = "") -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(filename(m, "md"), to_markdown(m))
        z.writestr(filename(m, "csv"), to_csv(m))
        z.writestr(filename(m, "ics"), to_ics(m))
        z.writestr(filename(m, "json"), to_json(m))
        z.writestr(f"{_slug(m.title)}-slack.txt", to_slack(m))
        z.writestr(f"{_slug(m.title)}-report.html", to_html(m))
        if emails_md:
            z.writestr(f"{_slug(m.title)}-email-drafts.md", emails_md)
    return buf.getvalue()


def emails_to_markdown(m: MeetingOut) -> str:
    out = []
    for em in m.emails:
        out += [f"## {em.subject}", f"_To: {em.to_addr or em.recipient or 'team'}_", "", em.body_text, "", "---", ""]
    return "\n".join(out)
